# ruff: noqa: F821 (PlatformIO injects Import and env into SCons scripts)
"""Compile a builder's update key, board name and firmware version into the OLED kit (hub ADR 012).

GROK_UPDATE_PUBLIC_KEY (or the environment option custom_update_public_key) names a PEM public
key, or the gateway's update fixture (a JSON file with "public_key"). Without one, the image
has no key and never asks for updates, so published build checksums stay comparable.
GROK_FIRMWARE_VERSION (or custom_firmware_version) replaces the version the image reports.
The key goes into a generated header in the build directory, never into the repository.
"""

import json
import os
import re
from pathlib import Path

Import("env")


def option(name, variable):
    return os.environ.get(variable) or env.GetProjectOption(name, "")


version = option("custom_firmware_version", "GROK_FIRMWARE_VERSION")
if version:
    if not re.fullmatch(r"[0-9A-Za-z][0-9A-Za-z.+_-]{0,31}", version):
        raise SystemExit(f"GROK_FIRMWARE_VERSION {version!r}: 1-32 letters, digits, . + _ -")
    env.Append(CPPDEFINES=[("OLED_KIT_VERSION", env.StringifyMacro(version))])

key_path = option("custom_update_public_key", "GROK_UPDATE_PUBLIC_KEY")
if key_path:
    path = Path(env.subst("$PROJECT_DIR")) / key_path
    text = path.read_text()
    if path.suffix == ".json":
        text = json.loads(text)["public_key"]
    if "BEGIN PUBLIC KEY" not in text or "PRIVATE" in text:
        raise SystemExit(f"{key_path} is not a PEM public key")
    board = env.GetProjectOption("custom_update_board", "") or env["PIOENV"]
    generated = Path(env.subst("$BUILD_DIR")) / "generated"
    generated.mkdir(parents=True, exist_ok=True)
    literal = json.dumps(text.strip() + "\n")  # A valid C string literal for ASCII PEM.
    (generated / "grok_update_key.h").write_text(
        "// Generated by tools/update_build.py; not in the repository.\n"
        "#pragma once\n"
        f"static const char GrokUpdateKey[] = {literal};\n"
        f"static const char GrokUpdateBoard[] = {json.dumps(board)};\n"
    )
    env.Append(CPPPATH=[str(generated)], CPPDEFINES=["GROK_UPDATE_KEY_HEADER"])
    print(f"Update key {key_path} compiled in for board {board}")
